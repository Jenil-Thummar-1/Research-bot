    def _call_groq(self, model: str, messages: list[dict[str, str]], timeout: float) -> str:
        """Execute non-streaming call to Groq Cloud API."""
        url = "https://api.groq.com/openai/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {self._groq_api_key}",
            "Content-Type": "application/json",
        }
        payload = {"model": model, "messages": messages, "stream": False}
        try:
            resp = requests.post(url, headers=headers, json=payload, timeout=timeout)
            if resp.status_code == 401:
                raise ChatAuthError("Groq API key is invalid or unauthorized. Verify your key at https://console.groq.com.")
            if resp.status_code == 429:
                raise ChatQuotaError("Groq rate limit exceeded. Please wait a moment.")
            if resp.status_code != 200:
                raise ChatServiceError(f"Groq API error {resp.status_code}: {resp.text}")
            data = resp.json()
            return data.get("choices", [{}])[0].get("message", {}).get("content", "").strip()
        except requests.exceptions.Timeout as err:
            raise ChatTimeoutError(f"Groq generation timed out after {timeout:.1f}s.") from err

    def _stream_groq(
        self,
        model: str,
        messages: list[dict[str, str]],
        timeout: float,
        should_stop_callback: Callable[[], bool] | None = None,
    ) -> Generator[str, None, None]:
        """Stream chunks from Groq Cloud API via Server-Sent Events."""
        url = "https://api.groq.com/openai/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {self._groq_api_key}",
            "Content-Type": "application/json",
        }
        payload = {"model": model, "messages": messages, "stream": True}
        try:
            resp = requests.post(url, headers=headers, json=payload, stream=True, timeout=timeout)
            if resp.status_code == 401:
                raise ChatAuthError("Groq API key is invalid or unauthorized. Verify your key at https://console.groq.com.")
            if resp.status_code == 429:
                raise ChatQuotaError("Groq rate limit exceeded. Please wait a moment.")
            if resp.status_code != 200:
                raise ChatServiceError(f"Groq API error {resp.status_code}: {resp.text}")

            for line in resp.iter_lines(decode_unicode=True):
                if should_stop_callback is not None and should_stop_callback():
                    break
                if line and line.startswith("data: "):
                    payload_str = line[6:].strip()
                    if payload_str == "[DONE]":
                        break
                    try:
                        data = json.loads(payload_str)
                        choices = data.get("choices", [])
                        if choices:
                            chunk = choices[0].get("delta", {}).get("content", "")
                            if chunk:
                                yield chunk
                    except json.JSONDecodeError:
                        continue
        except requests.exceptions.Timeout as err:
            raise ChatTimeoutError(f"Groq generation timed out after {timeout:.1f}s.") from err

    def _call_gemini_with_rotation(
        self,
        history: list[ChatMessage],
        clean_prompt: str,
        evidence_text: str | None,
        max_context_turns: int,
        timeout_seconds: float,
        preferred_model: str,
    ) -> tuple[str, str]:
        """Call Gemini model with key-pool rotation and fallback model support."""
        if not self._get_active_gemini_key():
            raise MissingChatKeyError("Gemini API key is missing. Add GEMINI_API_KEY to your .env file.")

        contents = format_conversation_for_gemini(
            history=history,
            current_prompt=clean_prompt,
            max_turns=max_context_turns,
            evidence_text=evidence_text,
        )

        timeout_ms = max(10000, int(timeout_seconds * 1000))
        config = types.GenerateContentConfig(
            system_instruction=self._system_instruction,
            temperature=0.7,
        )

        model_to_use = preferred_model
        keys_to_try = len(self._gemini_api_keys) if self._gemini_api_keys else 1

        for attempt in range(keys_to_try):
            active_key = self._get_active_gemini_key()
            client = genai.Client(
                api_key=active_key,
                http_options=types.HttpOptions(timeout=timeout_ms),
            )
            try:
                response = client.models.generate_content(
                    model=model_to_use,
                    contents=contents,
                    config=config,
                )
                raw_text = (response.text or "").strip()
                if not raw_text:
                    raise ChatServiceError("Received empty response from Gemini model.")
                return raw_text, model_to_use
            except ServerError as err:
                err_str = str(err).lower()
                if model_to_use != "gemini-3.5-flash":
                    try:
                        response = client.models.generate_content(
                            model="gemini-3.5-flash",
                            contents=contents,
                            config=config,
                        )
                        raw_text = (response.text or "").strip()
                        if not raw_text:
                            raise ChatServiceError("Received empty response from Gemini model.")
                        return raw_text, "gemini-3.5-flash"
                    except Exception as fb_err:
                        if "504" in str(fb_err).lower() or "deadline" in str(fb_err).lower():
                            raise ChatTimeoutError(f"Chat response timed out after {timeout_seconds:.1f}s.") from fb_err
                        raise ChatServiceError(f"Gemini server error: {err}") from err
                elif "504" in err_str or "deadline" in err_str or "timed out" in err_str:
                    raise ChatTimeoutError(f"Chat response timed out after {timeout_seconds:.1f}s.") from err
                raise ChatServiceError(f"Gemini server error: {err}") from err
            except ClientError as err:
                err_str = str(err).lower()
                if any(k in err_str for k in ("401", "403", "unauthorized", "api_key_invalid")):
                    raise ChatAuthError("Gemini API key is invalid or unauthorized. Verify your key at https://aistudio.google.com.") from err
                if any(k in err_str for k in ("429", "quota", "resource_exhausted")):
                    # Try rotating key in the pool
                    if attempt < keys_to_try - 1 and self._rotate_gemini_key():
                        logger.info("Retrying Gemini request with rotated key...")
                        continue
                    # Try falling back to gemini-3.5-flash
                    if model_to_use != "gemini-3.5-flash":
                        try:
                            response = client.models.generate_content(
                                model="gemini-3.5-flash",
                                contents=contents,
                                config=config,
                            )
                            raw_text = (response.text or "").strip()
                            if not raw_text:
                                raise ChatServiceError("Received empty response from Gemini model.")
                            return raw_text, "gemini-3.5-flash"
                        except Exception:
                            pass
                    raise ChatQuotaError(
                        "Gemini API quota or rate limit exceeded. "
                        "Free tier daily quota reached. Configure GROQ_API_KEY in .env for 14,400 free requests/day "
                        "or add additional Gemini keys to GEMINI_API_KEY."
                    ) from err
                raise ChatServiceError(f"Gemini client error: {err}") from err
            except APIError as err:
                err_str = str(err).lower()
                if "504" in err_str or "deadline" in err_str or "timed out" in err_str:
                    raise ChatTimeoutError(f"Chat response timed out after {timeout_seconds:.1f}s.") from err
                raise ChatServiceError(f"Gemini API error: {err}") from err

        raise ChatQuotaError(
            "All available Gemini API keys have exhausted their quota. "
            "Configure GROQ_API_KEY in .env for free Groq fallback or add more Gemini keys."
        )

    def _stream_gemini_with_rotation(
        self,
        history: list[ChatMessage],
        clean_prompt: str,
        evidence_text: str | None,
        max_context_turns: int,
        timeout_seconds: float,
        preferred_model: str,
        should_stop_callback: Callable[[], bool] | None = None,
        result_holder: StreamResult | None = None,
    ) -> Generator[tuple[str, str], None, None]:
        """Stream chunks from Gemini, handling server errors, model fallbacks, and quotas."""
        if not self._get_active_gemini_key():
            raise MissingChatKeyError("Gemini API key is missing. Add GEMINI_API_KEY to your .env file.")

        contents = format_conversation_for_gemini(
            history=history,
            current_prompt=clean_prompt,
            max_turns=max_context_turns,
            evidence_text=evidence_text,
        )

        timeout_ms = max(10000, int(timeout_seconds * 1000))
        config = types.GenerateContentConfig(
            system_instruction=self._system_instruction,
            temperature=0.7,
        )

        model_to_use = preferred_model
        client = genai.Client(
            api_key=self._get_active_gemini_key(),
            http_options=types.HttpOptions(timeout=timeout_ms),
        )

        def _init_stream(target_model: str):
            return client.models.generate_content_stream(
                model=target_model,
                contents=contents,
                config=config,
            )

        models_to_try = [model_to_use]
        if model_to_use != "gemini-3.5-flash":
            models_to_try.append("gemini-3.5-flash")

        stream_succeeded = False
        for m in models_to_try:
            try:
                stream = _init_stream(m)
                for chunk in stream:
                    if should_stop_callback is not None and should_stop_callback():
                        if result_holder is not None:
                            result_holder.stopped_early = True
                        break
                    text = chunk.text or ""
                    if text:
                        stream_succeeded = True
                        yield text, m
                if stream_succeeded:
                    return
            except ServerError as err:
                err_str = str(err).lower()
                if not stream_succeeded and m != models_to_try[-1]:
                    logger.warning("Gemini model %s server error (%s); falling back to %s", m, err, models_to_try[-1])
                    continue
                if "504" in err_str or "deadline" in err_str or "timed out" in err_str:
                    raise ChatTimeoutError(f"Chat response timed out after {timeout_seconds:.1f}s.") from err
                raise ChatServiceError(f"Gemini server error: {err}") from err
            except ClientError as err:
                err_str = str(err).lower()
                if any(k in err_str for k in ("401", "403", "unauthorized", "api_key_invalid")):
                    raise ChatAuthError("Gemini API key is invalid or unauthorized. Verify your key at https://aistudio.google.com.") from err
                if any(k in err_str for k in ("429", "quota", "resource_exhausted")):
                    if not stream_succeeded and m != models_to_try[-1]:
                        logger.warning("Gemini model %s hit quota; falling back to %s", m, models_to_try[-1])
                        continue
                    raise ChatQuotaError(
                        "Gemini API quota or rate limit exceeded. "
                        "Configure GROQ_API_KEY in .env for 14,400 free requests/day."
                    ) from err
                raise ChatServiceError(f"Gemini client error: {err}") from err
            except GeneratorExit:
                if result_holder is not None:
                    result_holder.stopped_early = True
                raise
