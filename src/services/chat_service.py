def should_auto_search(prompt: str) -> bool:
    """Detect whether a user query contains explicit cues requesting live web information."""
    if not prompt:
        return False
    lower_prompt = prompt.lower()
    return any(re.search(pattern, lower_prompt) for pattern in SEARCH_AUTO_KEYWORDS)


def format_conversation_for_gemini(
    history: Sequence[ChatMessage],
    current_prompt: str,
    max_turns: int = 12,
    evidence_text: str | None = None,
) -> list[types.Content]:
    """Format past chat history and current user prompt into Gemini types.Content objects."""
    selected_history = list(history)[-max_turns:] if max_turns > 0 else []

    formatted_contents: list[types.Content] = []

    for msg in selected_history:
        role = "user" if msg.role == "user" else "model"
        text = (msg.content or "").strip()
        if not text:
            continue

        if formatted_contents and formatted_contents[-1].role == role:
            existing_text = formatted_contents[-1].parts[0].text
            merged_text = f"{existing_text}\n\n{text}"
            formatted_contents[-1] = types.Content(
                role=role,
                parts=[types.Part.from_text(text=merged_text)],
            )
        else:
            formatted_contents.append(
                types.Content(
                    role=role,
                    parts=[types.Part.from_text(text=text)],
                )
            )

    if evidence_text:
        final_prompt = f"{evidence_text}\n\nUser Question:\n{current_prompt}"
    else:
        final_prompt = current_prompt

    if formatted_contents and formatted_contents[-1].role == "user":
        prev_text = formatted_contents[-1].parts[0].text
        formatted_contents[-1] = types.Content(
            role="user",
            parts=[types.Part.from_text(text=f"{prev_text}\n\n{final_prompt}")],
        )
    else:
        formatted_contents.append(
            types.Content(
                role="user",
                parts=[types.Part.from_text(text=final_prompt)],
            )
        )

    return formatted_contents


def format_conversation_for_openai(
    system_instruction: str,
    history: Sequence[ChatMessage],
    current_prompt: str,
    max_turns: int = 12,
    evidence_text: str | None = None,
) -> list[dict[str, str]]:
    """Format past chat history and prompt for OpenAI-compatible endpoints (e.g., Groq)."""
    messages = [{"role": "system", "content": system_instruction}]
    selected_history = list(history)[-max_turns:] if max_turns > 0 else []

    for msg in selected_history:
        role = "user" if msg.role == "user" else "assistant"
        content = (msg.content or "").strip()
        if content:
            messages.append({"role": role, "content": content})

    final_prompt = f"{evidence_text}\n\nUser Question:\n{current_prompt}" if evidence_text else current_prompt
    messages.append({"role": "user", "content": final_prompt})
    return messages


class ConversationalChatService:
    """Service orchestrating general conversational chat with multi-provider support."""

    def __init__(
        self,
        gemini_api_key: str | None = None,
        gemini_api_keys: list[str] | None = None,
        tavily_api_key: str | None = None,
        groq_api_key: str | None = None,
        provider: Literal["gemini", "groq"] | str | None = None,
        search_provider: Literal["auto", "tavily", "duckduckgo"] = "auto",
        model_name: str | None = None,
        system_instruction: str = DEFAULT_SYSTEM_INSTRUCTION,
        search_service: TavilySearchService | None = None,
    ):
        """Initialize the chat service."""
        if gemini_api_key is not None:
            self._gemini_api_keys = [gemini_api_key.strip()] if gemini_api_key.strip() else []
        elif gemini_api_keys is not None:
            self._gemini_api_keys = [k.strip() for k in gemini_api_keys if k.strip()]
        else:
            self._gemini_api_keys = get_gemini_api_keys()

        self._gemini_api_key = self._gemini_api_keys[0] if self._gemini_api_keys else ""
        self._current_key_idx = 0

        if groq_api_key is not None:
            self._groq_api_key = groq_api_key.strip()
        elif (gemini_api_key is not None) or (gemini_api_keys is not None):
            self._groq_api_key = (get_groq_api_key() or "").strip() if provider == "groq" else ""
        else:
            self._groq_api_key = (get_groq_api_key() or "").strip()

        # Resolve provider: explicit provider > explicit groq_api_key > explicit gemini_api_key > default from env
        if provider:
            self._provider = str(provider).lower()
        elif groq_api_key is not None and groq_api_key.strip():
            self._provider = "groq"
        elif (gemini_api_key is not None) or (gemini_api_keys is not None):
            self._provider = "gemini"
        else:
            self._provider = get_default_provider()

        if model_name:
            self._model_name = model_name
        else:
            self._model_name = DEFAULT_GROQ_MODEL if self._provider == "groq" else DEFAULT_GEMINI_MODEL

        self._search_provider = search_provider
        self._system_instruction = system_instruction
        self._search_service = search_service or TavilySearchService(api_key=tavily_api_key)

    @property
    def is_configured(self) -> bool:
        """Check whether the active provider (or any supported provider) is configured."""
        if self._provider == "groq":
            return bool(self._groq_api_key)
        return bool(self._gemini_api_key or self._gemini_api_keys)

    @property
    def model_name(self) -> str:
        """Return the active model name."""
        return self._model_name

    @property
    def provider(self) -> str:
        """Return the active provider."""
        return self._provider

    def _get_active_gemini_key(self) -> str:
        """Get the current Gemini key from the key rotation pool."""
        if not self._gemini_api_keys:
            return self._gemini_api_key
        return self._gemini_api_keys[self._current_key_idx % len(self._gemini_api_keys)]

    def _rotate_gemini_key(self) -> bool:
        """Advance to the next key in the pool on quota exhaustion. Returns True if rotated."""
        if len(self._gemini_api_keys) <= 1:
            return False
        self._current_key_idx = (self._current_key_idx + 1) % len(self._gemini_api_keys)
        self._gemini_api_key = self._get_active_gemini_key()
        logger.info(
            "Rotated to Gemini API key index %d of %d",
            self._current_key_idx + 1,
            len(self._gemini_api_keys),
        )
        return True

    def _execute_web_search(
        self,
        query: str,
        max_results: int = 4,
        timeout: float = 8.0,
    ) -> tuple[list[GroundedSource], str]:
        """Perform web search with keyless DuckDuckGo fallback and format sources."""
        try:
            results = self._search_service.search(
                query=query,
                max_results=max_results,
                search_depth="basic",
                timeout=timeout,
                provider=self._search_provider,
                fallback_to_ddg=True,
            )
        except SearchServiceError as err:
            logger.warning("Web search failed: %s; falling back to direct chat", err)
            return [], ""
        except Exception as err:
            logger.warning("Unexpected error during web search: %s; falling back to direct chat", err)
            return [], ""

        if not results:
            return [], ""

        sources: list[GroundedSource] = []
        blocks: list[str] = []
        for idx, res in enumerate(results, start=1):
            source_id = f"S{idx}"
            domain = extract_domain_name(res.url)
            grounded = GroundedSource(
                source_id=source_id,
                title=res.title or f"Source {idx}",
                url=res.url,
                content=res.content or "No snippet available.",
                domain=domain,
                score=res.score,
            )
            sources.append(grounded)
            blocks.append(
                f"[{source_id}] {grounded.title}\n"
                f"URL: {grounded.url}\n"
                f"Snippet: {grounded.content}"
            )

        evidence_text = (
            "--- LIVE WEB EVIDENCE RETRIEVED FROM SEARCH ---\n"
            + "\n\n".join(blocks)
            + "\n\nINSTRUCTIONS FOR WEB GROUNDING:\n"
            "- Incorporate facts from the web evidence above where accurate and helpful.\n"
            "- Cite sources inline using tags like [S1] or [S2] whenever referencing factual data.\n"
            "- If the web evidence does not answer the question or appears contradictory, note that transparently."
        )
        return sources, evidence_text

    def send_message(
        self,
        user_prompt: str,
        conversation_history: Sequence[ChatMessage] | None = None,
        use_web_search: bool = False,
        search_query: str | None = None,
        max_context_turns: int = 12,
        timeout_seconds: float = 25.0,
        provider: str | None = None,
        model_name: str | None = None,
    ) -> ChatResponse:
        """Send a conversational message and obtain a complete response."""
        clean_prompt = (user_prompt or "").strip()
        if not clean_prompt:
            raise ChatServiceError("User message cannot be empty.")

        active_provider = (provider or self._provider).lower()
        active_model = model_name or self._model_name
        start_time = time.perf_counter()
        history = list(conversation_history or [])

        # Determine if web search is needed
        run_search = use_web_search or should_auto_search(clean_prompt)
        sources: list[GroundedSource] = []
        evidence_text = ""
        effective_search_query = (search_query or clean_prompt).strip()

        if run_search and (self._search_service.is_configured or self._search_provider in ("duckduckgo", "auto")):
            sources, evidence_text = self._execute_web_search(
                query=effective_search_query,
                max_results=4,
                timeout=min(8.0, timeout_seconds * 0.4),
            )

        web_search_active = bool(sources)

        has_groq = bool(self._groq_api_key)
        has_gemini = bool(self._gemini_api_key or self._gemini_api_keys)

        if not has_groq and not has_gemini:
            if active_provider == "gemini":
                raise MissingChatKeyError(
                    "Gemini API key is missing. Add GEMINI_API_KEY to your .env file or get a key at https://aistudio.google.com."
                )
            if active_provider == "groq":
                raise MissingChatKeyError(
                    "Groq API key is missing. Add GROQ_API_KEY to your .env file or get a free key at https://console.groq.com."
                )
            raise MissingChatKeyError(
                "No AI provider is configured. Please provide a GROQ_API_KEY (free at https://console.groq.com) "
                "or GEMINI_API_KEY (free at https://aistudio.google.com) in your .env file or sidebar."
            )

        raw_text = ""
        effective_model = active_model
        effective_provider = active_provider

        # Attempt with active provider, with automatic failover between Groq and Gemini
        if active_provider == "groq":
            if not has_groq:
                if has_gemini:
                    logger.info("Groq key missing; failing over to Gemini")
                    raw_text, effective_model = self._call_gemini_with_rotation(
                        history=history,
                        clean_prompt=clean_prompt,
                        evidence_text=evidence_text if web_search_active else None,
                        max_context_turns=max_context_turns,
                        timeout_seconds=timeout_seconds,
                        preferred_model=DEFAULT_GEMINI_MODEL,
                    )
                    effective_provider = "gemini"
                else:
                    raise MissingChatKeyError(
                        "Groq API key is missing. Add GROQ_API_KEY to your .env file or get a free key at https://console.groq.com."
                    )
            else:
                target_model = active_model if active_model not in (DEFAULT_GEMINI_MODEL, "gemini-3.5-flash") else DEFAULT_GROQ_MODEL
                messages = format_conversation_for_openai(
                    system_instruction=self._system_instruction,
                    history=history,
                    current_prompt=clean_prompt,
                    max_turns=max_context_turns,
                    evidence_text=evidence_text if web_search_active else None,
                )
                try:
                    raw_text = self._call_groq(target_model, messages, timeout_seconds)
                    effective_model = target_model
                    effective_provider = "groq"
                except (ChatQuotaError, ChatTimeoutError, ChatServiceError) as err:
                    if has_gemini and not isinstance(err, ChatAuthError):
                        logger.warning("Groq call failed (%s); failing over to Gemini", err)
                        try:
                            raw_text, effective_model = self._call_gemini_with_rotation(
                                history=history,
                                clean_prompt=clean_prompt,
                                evidence_text=evidence_text if web_search_active else None,
                                max_context_turns=max_context_turns,
                                timeout_seconds=timeout_seconds,
                                preferred_model=DEFAULT_GEMINI_MODEL,
                            )
                            effective_provider = "gemini"
                        except Exception as gemini_err:
                            logger.warning("Gemini failover also failed: %s; re-raising primary Groq error", gemini_err)
                            raise err
                    else:
                        raise

        else:
            # Active provider: Gemini
            if not has_gemini:
                if has_groq:
                    logger.info("Gemini key missing; failing over to Groq")
                    target_model = DEFAULT_GROQ_MODEL
                    messages = format_conversation_for_openai(
                        system_instruction=self._system_instruction,
                        history=history,
                        current_prompt=clean_prompt,
                        max_turns=max_context_turns,
                        evidence_text=evidence_text if web_search_active else None,
                    )
                    raw_text = self._call_groq(target_model, messages, timeout_seconds)
                    effective_model = target_model
                    effective_provider = "groq"
                else:
                    raise MissingChatKeyError(
                        "Gemini API key is missing. Add GEMINI_API_KEY to your .env file or get a key at https://aistudio.google.com."
                    )
            else:
                try:
                    raw_text, effective_model = self._call_gemini_with_rotation(
                        history=history,
                        clean_prompt=clean_prompt,
                        evidence_text=evidence_text if web_search_active else None,
                        max_context_turns=max_context_turns,
                        timeout_seconds=timeout_seconds,
                        preferred_model=active_model,
                    )
                    effective_provider = "gemini"
                except (ChatQuotaError, ChatTimeoutError, ChatServiceError) as err:
                    if has_groq and not isinstance(err, ChatAuthError):
                        logger.warning("Gemini call failed (%s); failing over to Groq", err)
                        try:
                            target_model = DEFAULT_GROQ_MODEL
                            messages = format_conversation_for_openai(
                                system_instruction=self._system_instruction,
                                history=history,
                                current_prompt=clean_prompt,
                                max_turns=max_context_turns,
                                evidence_text=evidence_text if web_search_active else None,
                            )
                            raw_text = self._call_groq(target_model, messages, timeout_seconds)
                            effective_model = target_model
                            effective_provider = "groq"
                        except Exception as groq_err:
                            logger.warning("Groq failover also failed: %s; re-raising primary Gemini error", groq_err)
                            raise err
                    else:
                        raise

        # Bind citation links if search evidence was used
        final_text = raw_text
        if web_search_active and sources:
            sources_by_id = {src.source_id: src for src in sources}
            final_text = bind_citations_to_urls(raw_text, sources_by_id)

        elapsed = time.perf_counter() - start_time
        return ChatResponse(
            content=final_text,
            sources=sources,
            web_search_used=web_search_active,
            search_query=effective_search_query if web_search_active else "",
            model_used=effective_model,
            provider_used=effective_provider,
            elapsed_seconds=round(elapsed, 2),
        )

    def stream_message(
        self,
        user_prompt: str,
        conversation_history: Sequence[ChatMessage] | None = None,
        use_web_search: bool = False,
        search_query: str | None = None,
        max_context_turns: int = 12,
        timeout_seconds: float = 25.0,
        result_holder: StreamResult | None = None,
        should_stop_callback: Callable[[], bool] | None = None,
        provider: str | None = None,
        model_name: str | None = None,
    ) -> Generator[str, None, None]:
        """Stream a conversational response incrementally with automatic failover support."""
        clean_prompt = (user_prompt or "").strip()
        if not clean_prompt:
            raise ChatServiceError("User message cannot be empty.")

        active_provider = (provider or self._provider).lower()
        active_model = model_name or self._model_name
        start_time = time.perf_counter()
        history = list(conversation_history or [])

        # Determine if web search is needed
        run_search = use_web_search or should_auto_search(clean_prompt)
        sources: list[GroundedSource] = []
        evidence_text = ""
        effective_search_query = (search_query or clean_prompt).strip()

        if run_search and (self._search_service.is_configured or self._search_provider in ("duckduckgo", "auto")):
            sources, evidence_text = self._execute_web_search(
                query=effective_search_query,
                max_results=4,
                timeout=min(8.0, timeout_seconds * 0.4),
            )

        web_search_active = bool(sources)

        has_groq = bool(self._groq_api_key)
        has_gemini = bool(self._gemini_api_key or self._gemini_api_keys)

        if not has_groq and not has_gemini:
            if active_provider == "gemini":
                raise MissingChatKeyError(
                    "Gemini API key is missing. Add GEMINI_API_KEY to your .env file or get a key at https://aistudio.google.com."
                )
            if active_provider == "groq":
                raise MissingChatKeyError(
                    "Groq API key is missing. Add GROQ_API_KEY to your .env file or get a free key at https://console.groq.com."
                )
            raise MissingChatKeyError(
                "No AI provider is configured. Please provide a GROQ_API_KEY (free at https://console.groq.com) "
                "or GEMINI_API_KEY (free at https://aistudio.google.com) in your .env file or sidebar."
            )

        if result_holder is not None:
            result_holder.sources = sources
            result_holder.web_search_used = web_search_active
            result_holder.search_query = effective_search_query if web_search_active else ""
            result_holder.provider_used = active_provider

        accumulated_chunks: list[str] = []
        first_token_time: float | None = None
        effective_model = active_model
        effective_provider = active_provider

        try:
            if active_provider == "groq":
                if not has_groq and has_gemini:
                    logger.info("Groq key missing; failing over to Gemini streaming")
                    active_provider = "gemini"
                    effective_provider = "gemini"
                elif not has_groq:
                    raise MissingChatKeyError(
                        "Groq API key is missing. Add GROQ_API_KEY to your .env file or get a free key at https://console.groq.com."
                    )
                else:
                    target_model = active_model if active_model not in (DEFAULT_GEMINI_MODEL, "gemini-3.5-flash") else DEFAULT_GROQ_MODEL
                    effective_model = target_model
                    effective_provider = "groq"
                    messages = format_conversation_for_openai(
                        system_instruction=self._system_instruction,
                        history=history,
                        current_prompt=clean_prompt,
                        max_turns=max_context_turns,
                        evidence_text=evidence_text if web_search_active else None,
                    )
                    try:
                        stream_iter = self._stream_groq(target_model, messages, timeout_seconds, should_stop_callback)
                        for chunk in stream_iter:
                            if should_stop_callback is not None and should_stop_callback():
                                if result_holder is not None:
                                    result_holder.stopped_early = True
                                break
                            if chunk:
                                if first_token_time is None:
                                    first_token_time = time.perf_counter() - start_time
                                    if result_holder is not None:
                                        result_holder.time_to_first_token = round(first_token_time, 2)
                                accumulated_chunks.append(chunk)
                                yield chunk
                    except (ChatQuotaError, ChatTimeoutError, ChatServiceError) as err:
                        if has_gemini and not accumulated_chunks and not isinstance(err, ChatAuthError):
                            logger.warning("Groq stream failed (%s); failing over to Gemini streaming", err)
                            active_provider = "gemini"
                            effective_provider = "gemini"
                        else:
                            raise

            if active_provider == "gemini":
                if not has_gemini and has_groq:
                    logger.info("Gemini key missing; failing over to Groq streaming")
                    target_model = DEFAULT_GROQ_MODEL
                    effective_model = target_model
                    effective_provider = "groq"
                    messages = format_conversation_for_openai(
                        system_instruction=self._system_instruction,
                        history=history,
                        current_prompt=clean_prompt,
                        max_turns=max_context_turns,
                        evidence_text=evidence_text if web_search_active else None,
                    )
                    stream_iter = self._stream_groq(target_model, messages, timeout_seconds, should_stop_callback)
                    for chunk in stream_iter:
                        if should_stop_callback is not None and should_stop_callback():
                            if result_holder is not None:
                                result_holder.stopped_early = True
                            break
                        if chunk:
                            if first_token_time is None:
                                first_token_time = time.perf_counter() - start_time
                                if result_holder is not None:
                                    result_holder.time_to_first_token = round(first_token_time, 2)
                            accumulated_chunks.append(chunk)
                            yield chunk
                elif not has_gemini:
                    raise MissingChatKeyError(
                        "Gemini API key is missing. Add GEMINI_API_KEY to your .env file or get a key at https://aistudio.google.com."
                    )
                else:
                    gemini_model = active_model if active_model in (DEFAULT_GEMINI_MODEL, "gemini-3.5-flash") else DEFAULT_GEMINI_MODEL
                    effective_model = gemini_model
                    effective_provider = "gemini"
                    try:
                        gemini_gen = self._stream_gemini_with_rotation(
                            history=history,
                            clean_prompt=clean_prompt,
                            evidence_text=evidence_text if web_search_active else None,
                            max_context_turns=max_context_turns,
                            timeout_seconds=timeout_seconds,
                            preferred_model=gemini_model,
                            should_stop_callback=should_stop_callback,
                            result_holder=result_holder,
                        )
                        for chunk, m_used in gemini_gen:
                            effective_model = m_used
                            if should_stop_callback is not None and should_stop_callback():
                                if result_holder is not None:
                                    result_holder.stopped_early = True
                                break
                            if chunk:
                                if first_token_time is None:
                                    first_token_time = time.perf_counter() - start_time
                                    if result_holder is not None:
                                        result_holder.time_to_first_token = round(first_token_time, 2)
                                accumulated_chunks.append(chunk)
                                yield chunk
                    except (ChatQuotaError, ChatTimeoutError, ChatServiceError) as err:
                        if has_groq and not accumulated_chunks and not isinstance(err, ChatAuthError):
                            logger.warning("Gemini stream failed (%s); failing over to Groq streaming", err)
                            target_model = DEFAULT_GROQ_MODEL
                            effective_model = target_model
                            effective_provider = "groq"
                            messages = format_conversation_for_openai(
                                system_instruction=self._system_instruction,
                                history=history,
                                current_prompt=clean_prompt,
                                max_turns=max_context_turns,
                                evidence_text=evidence_text if web_search_active else None,
                            )
                            stream_iter = self._stream_groq(target_model, messages, timeout_seconds, should_stop_callback)
                            for chunk in stream_iter:
                                if should_stop_callback is not None and should_stop_callback():
                                    if result_holder is not None:
                                        result_holder.stopped_early = True
                                    break
                                if chunk:
                                    if first_token_time is None:
                                        first_token_time = time.perf_counter() - start_time
                                        if result_holder is not None:
                                            result_holder.time_to_first_token = round(first_token_time, 2)
                                    accumulated_chunks.append(chunk)
                                    yield chunk
                        else:
                            raise

        except GeneratorExit:
            if result_holder is not None:
                result_holder.stopped_early = True
            raise
        finally:
            elapsed = time.perf_counter() - start_time
            raw_text = "".join(accumulated_chunks).strip()
            final_text = raw_text
            if web_search_active and sources and raw_text:
                sources_by_id = {src.source_id: src for src in sources}
                final_text = bind_citations_to_urls(raw_text, sources_by_id)

            if result_holder is not None:
                result_holder.full_content = final_text
                result_holder.total_elapsed_seconds = round(elapsed, 2)
                result_holder.model_used = effective_model
                result_holder.provider_used = effective_provider
                if first_token_time is not None:
                    result_holder.time_to_first_token = round(first_token_time, 2)

